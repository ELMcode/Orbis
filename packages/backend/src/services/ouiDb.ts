/**
 * Normalize a raw MAC/EUI-48 address to a 12-char uppercase hex string
 * (colons, dashes, dots and spaces stripped). Returns null when the value
 * does not contain exactly 12 hex digits.
 */
export function normalizeMacToHex(mac: string): string | null {
  const hex = mac.replace(/[^0-9a-fA-F]/g, '').toUpperCase();
  return hex.length === 12 ? hex : null;
}

/**
 * Extract the 6-char OUI (first 3 bytes) from a raw MAC address.
 * Returns the OUI in uppercase without separators, or null for invalid input.
 */
export function extractOui(mac: string): string | null {
  const hex = normalizeMacToHex(mac);
  return hex ? hex.slice(0, 6) : null;
}

/**
 * Look up the vendor for a raw 6-char OUI (uppercase, no separators).
 * Pass through {@link extractOui} first when starting from a full MAC.
 */
export function lookupVendorByOui(oui: string): string | null {
  if (!oui) return null;
  const normalized = oui.replace(/[^0-9a-fA-F]/g, '').toUpperCase().slice(0, 6);
  if (normalized.length !== 6) return null;
  return OUI_DB[normalized] ?? null;
}

/**
 * Look up the vendor for a MAC/EUI-48 address.
 *
 * @param mac A MAC address in any common format (`aa:bb:cc:dd:ee:ff`,
 *            `AA-BB-CC-DD-EE-FF`, `aabb.ccdd.eeff`, `aabbccddeeff`, ...).
 * @returns The vendor name, or `null` when the OUI is unknown.
 */
export function lookupVendorByMac(mac: string): string | null {
  const oui = extractOui(mac);
  if (!oui) return null;
  return OUI_DB[oui] ?? null;
}

